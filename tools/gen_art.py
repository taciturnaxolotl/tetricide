# Logo letters on a grid of blocks, 5 rows tall. Each letter takes the
# color of a tetromino: 1 I, 2 O, 3 T, 4 S, 5 Z, 6 J, 7 L.
LOGO_LETTERS = [
    ("T", 5, ["###", ".#.", ".#.", ".#.", ".#."]),
    ("E", 7, ["###", "#..", "##.", "#..", "###"]),
    ("T", 2, ["###", ".#.", ".#.", ".#.", ".#."]),
    ("R", 4, ["##.", "#.#", "##.", "#.#", "#.#"]),
    ("I", 1, ["###", ".#.", ".#.", ".#.", "###"]),
    ("C", 3, [".##", "#..", "#..", "#..", ".##"]),
    ("I", 1, ["###", ".#.", ".#.", ".#.", "###"]),
    ("D", 6, ["##.", "#.#", "#.#", "#.#", "##."]),
    ("E", 5, ["###", "#..", "##.", "#..", "###"]),
]

# Background: deep navy at the top to plum at the bottom, as 4-bit RGB.
GRAD_TOP = (0x1, 0x1, 0x3)
GRAD_BOT = (0x4, 0x1, 0x5)


def font_vhd():
    lines = []
    for code in range(32, 96):
        ch = chr(code)
        rows = FONT.get(ch, FONT[" "])
        bits = "".join(rows).replace("#", "1").replace(".", "0")
        lines.append(f'        "{bits}"{"," if code < 95 else " "}  -- {ch!r}')
    return "\n".join(lines)


def logo_grid():
    rows = ["" for _ in range(5)]
    for i, (_, color, glyph) in enumerate(LOGO_LETTERS):
        for r in range(5):
            rows[r] += "".join(str(color) if ch == "#" else "0" for ch in glyph[r])
            if i < len(LOGO_LETTERS) - 1:
                rows[r] += "0"
    return rows


def grad():
    out = []
    for i in range(16):
        c = [round(a + (b - a) * i / 15) for a, b in zip(GRAD_TOP, GRAD_BOT)]
        out.append("x\"" + "".join(f"{v:X}" for v in c) + "\"")
    return out


def main():
    logo = logo_grid()
    width = len(logo[0])
    logo_rows = ",\n".join(
        "        (" + ", ".join(ch for ch in row) + ")" for row in logo)
    vhd = f"""-- Generated by tools/gen_art.py. Do not edit.
library ieee;
use ieee.std_logic_1164.all;

package art is
    -- ASCII 32..95, 5x7 bits row-major, bit 0 = top-left
    type font_t is array (32 to 95) of std_logic_vector(0 to 34);
    constant FONT : font_t := (
{font_vhd()}
    );

    constant LOGO_W : integer := {width};
    constant LOGO_H : integer := 5;
    type logo_t is array (0 to LOGO_H - 1, 0 to LOGO_W - 1) of integer range 0 to 7;
    constant LOGO : logo_t := (
{logo_rows}
    );

    type grad_t is array (0 to 15) of std_logic_vector(11 downto 0);
    constant GRAD : grad_t := ({", ".join(grad())});
end art;
"""
    out = Path(__file__).resolve().parent.parent / "src" / "art.vhd"
    out.write_text(vhd)
    print(f"wrote {out} (logo {width} x 5 blocks)")


if __name__ == "__main__":
    main()
