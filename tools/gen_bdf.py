#!/usr/bin/env python3
"""Write the Quartus schematic for Tetricide.

    quartus/tetricide_top.bdf   the top-level block diagram
    quartus/<block>.bsf         one symbol per VHDL block
    docs/schematic.svg          a preview of the same drawing

Blocks are connected by named wires, the way the lab's LAB8.bdf is: every
port gets a short stub with its net name on it, and Quartus joins wires that
share a name. Input pins connect by their own pin name (SW[9] reaches the
SW[9..0] pin); output pins get a wire with an internal name.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CW = 6  # rough Arial character width at the default size

HEADER = """/*
WARNING: Do NOT edit the input and output ports in this file in a text
editor if you plan to continue editing the block that represents it in
the Block Editor! File corruption is VERY likely to occur.
*/
/*
Generated by tools/gen_bdf.py for Tetricide.
*/
"""

# (entity, inputs, outputs); a port is (name, width)
BLOCKS = {
    "clk_div2": ([("clk_in", 1)], [("clk_out", 1)]),
    "vga_timing": ([("clk", 1)],
                   [("h_sync", 1), ("v_sync", 1), ("video_on", 1),
                    ("pixel_row", 10), ("pixel_col", 10)]),
    "tetris_core": ([("clk", 1), ("reset_n", 1), ("ps2_clk", 1), ("ps2_data", 1),
                     ("vert_sync", 1), ("pixel_row", 10), ("pixel_col", 10),
                     ("start_level", 4), ("force_piece", 3), ("show_ghost", 1)],
                    [("red", 4), ("green", 4), ("blue", 4), ("lines_bcd", 16),
                     ("level_bcd", 8), ("game_over", 1)]),
    "vga_out": ([("clk", 1), ("h_sync", 1), ("v_sync", 1), ("video_on", 1),
                 ("red", 4), ("green", 4), ("blue", 4)],
                [("vga_r", 4), ("vga_g", 4), ("vga_b", 4), ("vga_hs", 1), ("vga_vs", 1)]),
    "hex4": ([("bcd", 16)],
             [("hex3", 7), ("hex2", 7), ("hex1", 7), ("hex0", 7)]),
}

STUB = 96


def label(name, w):
    return f"{name}[{w - 1}..0]" if w > 1 else name


def tw(s):
    return len(s) * CW + 2


def geometry(ins, outs):
    lin = max((tw(label(n, w)) for n, w in ins), default=0)
    lout = max((tw(label(n, w)) for n, w in outs), default=0)
    w = 16 + 21 + lin + 24 + lout + 21 + 16
    w = (w + 7) // 8 * 8
    h = 32 + 16 * max(len(ins), len(outs)) + 16
    return w, h


def _w(ent):
    ins, outs = BLOCKS[ent]
    return geometry(ins, outs)[0]


COL3 = 840 + _w("tetris_core") + 2 * STUB + 64
OUT_X = COL3 + _w("vga_out") + 2 * STUB + 64

# instance: entity, position, net on each port
INSTANCES = [
    ("clk_div2", (360, 64), {
        "clk_in": "CLOCK_50", "clk_out": "clk25"}),
    ("vga_timing", (360, 200), {
        "clk": "clk25", "h_sync": "hs", "v_sync": "vs", "video_on": "video_on",
        "pixel_row": "row[9..0]", "pixel_col": "col[9..0]"}),
    ("tetris_core", (840, 64), {
        "clk": "clk25", "reset_n": "KEY[0]", "ps2_clk": "PS2_CLK", "ps2_data": "PS2_DAT",
        "vert_sync": "vs", "pixel_row": "row[9..0]", "pixel_col": "col[9..0]",
        "start_level": "SW[3..0]", "force_piece": "hi,hi,hi", "show_ghost": "SW[9]",
        "red": "r[3..0]", "green": "g[3..0]", "blue": "b[3..0]",
        "lines_bcd": "lines[15..0]", "level_bcd": "o_ledg[7..0]", "game_over": "o_ledr9"}),
    ("vga_out", (COL3, 64), {
        "clk": "clk25", "h_sync": "hs", "v_sync": "vs", "video_on": "video_on",
        "red": "r[3..0]", "green": "g[3..0]", "blue": "b[3..0]",
        "vga_r": "o_vga_r[3..0]", "vga_g": "o_vga_g[3..0]", "vga_b": "o_vga_b[3..0]",
        "vga_hs": "o_vga_hs", "vga_vs": "o_vga_vs"}),
    ("hex4", (COL3, 352), {
        "bcd": "lines[15..0]",
        "hex3": "o_hex3[6..0]", "hex2": "o_hex2[6..0]",
        "hex1": "o_hex1[6..0]", "hex0": "o_hex0[6..0]"}),
]

# input pins (name, y); output pins (name, net, y)
INPUTS = [("CLOCK_50", 96), ("KEY[3..0]", 400), ("SW[9..0]", 432),
          ("PS2_CLK", 464), ("PS2_DAT", 496)]
OUTPUTS = [("VGA_R[3..0]", "o_vga_r[3..0]", 96), ("VGA_G[3..0]", "o_vga_g[3..0]", 128),
           ("VGA_B[3..0]", "o_vga_b[3..0]", 160), ("VGA_HS", "o_vga_hs", 192),
           ("VGA_VS", "o_vga_vs", 224),
           ("HEX3[6..0]", "o_hex3[6..0]", 384), ("HEX2[6..0]", "o_hex2[6..0]", 416),
           ("HEX1[6..0]", "o_hex1[6..0]", 448), ("HEX0[6..0]", "o_hex0[6..0]", 480),
           ("LEDG[7..0]", "o_ledg[7..0]", 544), ("LEDR[9]", "o_ledr9", 576)]
IN_X = 0
VCC_AT = (600, 520)


def text(s, x0, y0, extra=""):
    return f'(text "{s}" (rect {x0} {y0} {x0 + tw(s)} {y0 + 12})(font "Arial" ){extra})'


def symbol_body(entity, inst=None, at=None):
    ins, outs = BLOCKS[entity]
    w, h = geometry(ins, outs)
    if at:
        x, y = at
        head = f"(symbol\n\t(rect {x} {y} {x + w} {y + h})\n"
    else:
        head = f"(symbol\n\t(rect 16 16 {16 + w} {16 + h})\n"
    out = [head, f"\t{text(entity, 5, 0)}\n", f"\t{text(inst or 'inst', 8, h - 16)}\n"]
    for i, (n, wd) in enumerate(ins):
        py = 32 + 16 * i
        lb = label(n, wd)
        lw = 3 if wd > 1 else 1
        out.append(f"\t(port\n\t\t(pt 0 {py})\n\t\t(input)\n\t\t{text(lb, 0, 0)}\n"
                   f"\t\t{text(lb, 21, py - 5)}\n"
                   f"\t\t(line (pt 0 {py})(pt 16 {py})(line_width {lw}))\n\t)\n")
    for i, (n, wd) in enumerate(outs):
        py = 32 + 16 * i
        lb = label(n, wd)
        lw = 3 if wd > 1 else 1
        out.append(f"\t(port\n\t\t(pt {w} {py})\n\t\t(output)\n\t\t{text(lb, 0, 0)}\n"
                   f"\t\t{text(lb, w - 21 - tw(lb), py - 5)}\n"
                   f"\t\t(line (pt {w} {py})(pt {w - 16} {py})(line_width {lw}))\n\t)\n")
    out.append(f"\t(drawing\n\t\t(rectangle (rect 16 16 {w - 16} {h - 16})(line_width 1))\n\t)\n)\n")
    return "".join(out)


def is_bus(net):
    return "[" in net and ".." in net or "," in net


def connector(x1, y1, x2, y2, net=None, bus=False):
    lab = ""
    if net:
        lx = min(x1, x2) + 4
        lab = f"\t{text(net, lx, y1 - 16)}\n"
    return (f"(connector\n{lab}\t(pt {x1} {y1})\n\t(pt {x2} {y2})\n"
            f"{chr(9) + '(bus)' + chr(10) if bus else ''})\n")


def in_pin(name, y):
    x = IN_X
    return (f"(pin\n\t(input)\n\t(rect {x} {y - 8} {x + 168} {y + 8})\n"
            f'\t(text "INPUT" (rect 133 0 161 10)(font "Arial" (font_size 6)))\n'
            f"\t{text(name, 9, 0)}\n\t(pt 168 8)\n"
            "\t(drawing\n"
            "\t\t(line (pt 92 12)(pt 117 12)(line_width 1))\n"
            "\t\t(line (pt 92 4)(pt 117 4)(line_width 1))\n"
            "\t\t(line (pt 121 8)(pt 168 8)(line_width 1))\n"
            "\t\t(line (pt 92 12)(pt 92 4)(line_width 1))\n"
            "\t\t(line (pt 117 4)(pt 121 8)(line_width 1))\n"
            "\t\t(line (pt 117 12)(pt 121 8)(line_width 1))\n"
            "\t)\n"
            '\t(text "VCC" (rect 136 7 156 17)(font "Arial" (font_size 6)))\n)\n')


def out_pin(name, y):
    x = OUT_X
    return (f"(pin\n\t(output)\n\t(rect {x} {y - 8} {x + 176} {y + 8})\n"
            f'\t(text "OUTPUT" (rect 1 0 39 10)(font "Arial" (font_size 6)))\n'
            f"\t{text(name, 90, 0)}\n\t(pt 0 8)\n"
            "\t(drawing\n"
            "\t\t(line (pt 0 8)(pt 52 8)(line_width 1))\n"
            "\t\t(line (pt 52 4)(pt 78 4)(line_width 1))\n"
            "\t\t(line (pt 52 12)(pt 78 12)(line_width 1))\n"
            "\t\t(line (pt 52 12)(pt 52 4)(line_width 1))\n"
            "\t\t(line (pt 78 4)(pt 82 8)(line_width 1))\n"
            "\t\t(line (pt 82 8)(pt 78 12)(line_width 1))\n"
            "\t\t(line (pt 78 12)(pt 82 8)(line_width 1))\n"
            "\t)\n)\n")


def vcc(x, y):
    return (f"(symbol\n\t(rect {x} {y} {x + 32} {y + 16})\n"
            f'\t(text "VCC" (rect 7 0 27 10)(font "Arial" (font_size 6)))\n'
            f'\t(text "inst_vcc" (rect 3 5 43 17)(font "Arial" )(invisible))\n'
            "\t(port\n\t\t(pt 16 16)\n\t\t(output)\n"
            '\t\t(text "1" (rect 19 7 24 19)(font "Courier New" (bold))(invisible))\n'
            '\t\t(text "1" (rect 19 7 24 19)(font "Courier New" (bold))(invisible))\n'
            "\t\t(line (pt 16 16)(pt 16 8)(line_width 1))\n\t)\n"
            "\t(drawing\n\t\t(line (pt 8 8)(pt 24 8)(line_width 1))\n\t)\n)\n")


def build():
    parts = [HEADER, '(header "graphic" (version "1.3"))\n']
    svg = []  # (kind, ...) records for the preview
    for name, y in INPUTS:
        parts.append(in_pin(name, y))
        parts.append(connector(IN_X + 168, y, IN_X + 168 + 24, y, bus="[" in name))
        svg.append(("in", name, IN_X, y))
    for name, net, y in OUTPUTS:
        parts.append(out_pin(name, y))
        parts.append(connector(OUT_X - STUB, y, OUT_X, y, net, is_bus(net)))
        svg.append(("out", name, OUT_X, y, net))
    for i, (ent, (x, y), nets) in enumerate(INSTANCES):
        ins, outs = BLOCKS[ent]
        w, h = geometry(ins, outs)
        parts.append(symbol_body(ent, f"inst{i + 1}", (x, y)))
        svg.append(("blk", ent, x, y, w, h))
        for j, (n, wd) in enumerate(ins):
            py = y + 32 + 16 * j
            net = nets[n]
            parts.append(connector(x - STUB, py, x, py, net, wd > 1))
            svg.append(("stub", net, x - STUB, py, x, py, wd > 1, n, "in"))
        for j, (n, wd) in enumerate(outs):
            py = y + 32 + 16 * j
            net = nets[n]
            parts.append(connector(x + w, py, x + w + STUB, py, net, wd > 1))
            svg.append(("stub", net, x + w, py, x + w + STUB, py, wd > 1, n, "out"))
    vx, vy = VCC_AT
    parts.append(vcc(vx, vy))
    parts.append(connector(vx + 16, vy + 16, vx + 16, vy + 40))
    parts.append(connector(vx + 16, vy + 40, vx + 16 + STUB, vy + 40, "hi"))
    svg.append(("vcc", vx, vy))
    parts.append(f'(text "Tetricide  -  Kieran Klukas + Nathan Crosby" '
                 f'(rect 0 0 280 14)(font "Arial" (font_size 10)))\n')
    return "".join(parts), svg


def preview(items):
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-20 -20 {OUT_X + 240} 660" '
           'font-family="Arial" font-size="11"><rect x="-20" y="-20" width="{OUT_X + 240}" '
           f'height="660" fill="white"/>',
           '<text x="0" y="12" font-size="14">Tetricide  -  Kieran Klukas + Nathan Crosby</text>']
    for it in items:
        if it[0] == "blk":
            _, ent, x, y, w, h = it
            out.append(f'<rect x="{x + 16}" y="{y + 16}" width="{w - 32}" height="{h - 32}" '
                       'fill="white" stroke="black"/>')
            out.append(f'<text x="{x + 5}" y="{y + 11}">{ent}</text>')
        elif it[0] == "stub":
            _, net, x1, y1, x2, y2, bus, port, d = it
            sw = 3 if bus else 1
            col = "#800080"
            out.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{col}" stroke-width="{sw}"/>')
            out.append(f'<text x="{min(x1, x2) + 4}" y="{y1 - 3}" fill="#800080" font-size="9">{net}</text>')
            if d == "in":
                out.append(f'<text x="{x2 + 21}" y="{y2 + 4}" font-size="10">{port}</text>')
            else:
                out.append(f'<text x="{x1 - 21}" y="{y1 + 4}" font-size="10" text-anchor="end">{port}</text>')
        elif it[0] == "in":
            _, name, x, y = it
            out.append(f'<path d="M{x + 92} {y - 4} h25 l4 4 l-4 4 h-25 z M{x + 121} {y} H{x + 192}" '
                       'fill="none" stroke="black"/>')
            out.append(f'<text x="{x + 9}" y="{y + 4}">{name}</text>')
        elif it[0] == "out":
            _, name, x, y, net = it
            out.append(f'<path d="M{x - STUB} {y} H{x + 52} M{x + 52} {y - 4} h26 l4 4 l-4 4 h-26 z" '
                       'fill="none" stroke="black"/>')
            out.append(f'<text x="{x + 90}" y="{y + 4}">{name}</text>')
            out.append(f'<text x="{x - STUB + 4}" y="{y - 3}" fill="#800080" font-size="9">{net}</text>')
        elif it[0] == "vcc":
            _, x, y = it
            out.append(f'<path d="M{x + 8} {y + 8} H{x + 24} M{x + 16} {y + 8} V{y + 40} H{x + 64}" '
                       'fill="none" stroke="black"/>')
            out.append(f'<text x="{x + 7}" y="{y + 4}" font-size="8">VCC</text>')
            out.append(f'<text x="{x + 20}" y="{y + 37}" fill="#800080" font-size="9">hi</text>')
    out.append("</svg>\n")
    return "\n".join(out)


def main():
    q = ROOT / "quartus"
    q.mkdir(exist_ok=True)
    bdf, items = build()
    (q / "tetricide_top.bdf").write_text(bdf)
    for ent in BLOCKS:
        (q / f"{ent}.bsf").write_text(HEADER + '(header "symbol" (version "1.1"))\n' + symbol_body(ent))
    (ROOT / "docs" / "schematic.svg").write_text(preview(items))
    print("wrote quartus/tetricide_top.bdf, quartus/*.bsf, docs/schematic.svg")


if __name__ == "__main__":
    main()
