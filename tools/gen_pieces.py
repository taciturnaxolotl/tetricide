#!/usr/bin/env python3
"""Write src/pieces.vhd: 28 16-bit masks (7 shapes x 4 clockwise rotations).

Shapes are SRS spawn orientations. JLSTZ rotate inside a 3x3 box, I inside
4x4, O does not rotate. Bit 15 - (4r + c) is row r, column c.
"""
from pathlib import Path

SHAPES = {
    "I": ["....", "####", "....", "...."],
    "O": [".##.", ".##.", "....", "...."],
    "T": [".#.", "###", "..."],
    "S": [".##", "##.", "..."],
    "Z": ["##.", ".##", "..."],
    "J": ["#..", "###", "..."],
    "L": ["..#", "###", "..."],
}


def rotate(grid):
    n = len(grid)
    return ["".join(grid[n - 1 - c][r] for c in range(n)) for r in range(n)]


def to_mask(grid):
    bits = 0
    for r, line in enumerate(grid):
        for c, ch in enumerate(line):
            if ch == "#":
                bits |= 1 << (15 - (4 * r + c))
    return bits


def rotations(name):
    grid = SHAPES[name]
    out = []
    for _ in range(4):
        out.append(grid)
        if name != "O":
            grid = rotate(grid)
    return out


def main():
    entries = [(name, rot, to_mask(grid))
               for name in SHAPES for rot, grid in enumerate(rotations(name))]
    body = "\n".join(
        f'        x"{mask:04X}"{"," if i < len(entries) - 1 else " "}  -- {name} rot {rot}'
        for i, (name, rot, mask) in enumerate(entries))
    vhd = f"""-- Generated by tools/gen_pieces.py. Do not edit.
library ieee;
use ieee.std_logic_1164.all;

package pieces is
    type mask_rom_t is array (0 to 27) of std_logic_vector(15 downto 0);
    constant PIECE_ROM : mask_rom_t := (
{body}
    );
    function mask_bit(s, rt, r, c : integer) return std_logic;
end pieces;

package body pieces is
    function mask_bit(s, rt, r, c : integer) return std_logic is
        variable m : std_logic_vector(15 downto 0);
    begin
        m := PIECE_ROM(s * 4 + rt);
        return m(15 - (r * 4 + c));
    end mask_bit;
end pieces;
"""
    out = Path(__file__).resolve().parent.parent / "src" / "pieces.vhd"
    out.parent.mkdir(exist_ok=True)
    out.write_text(vhd)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
